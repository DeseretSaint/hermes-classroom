#!/usr/bin/env python3
"""Render the adopted fox to a standalone proof page: the painted 208 and the seven-pose set.

CP-005f's acceptance is a 208 px render of the painted ``clock`` and ``wave`` pose, because a
128 px frame does not prove identity parity with the signed A1 sheet. Home at 208 is CP-053's and
the Home quality pass's surface, not this card's, so the proof is generated from the shipped
module's own primitive: it mounts ``FoxPose`` at width 1344 inside the same ``CbV3Scope`` the route
uses, and every plate in the page is the encoded painted WebP the brand-asset segment ships.

``tests/test_cp010_fox_assets.py`` re-runs this generator and fails when the committed page differs
from a fresh render, so the frame cannot drift from ``desktop/plugin.js``.

Usage:
  python3 scripts/gen-fox-proof.py [--out design/fox-adoption.html] [--check]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLUGIN_JS = ROOT / "desktop" / "plugin.js"
DEFAULT_OUT = ROOT / "design" / "fox-adoption.html"

#: The two poses the acceptance names, then the whole set at the size each assigned surface uses.
HERO = [("wave", 208, "Home trailhead — wave at 208"),
        ("clock", 208, "Home / New course — clock at 208")]
STRIP = [("wave", 96, "Home trailhead"),
         ("point", 96, "Discover feature"),
         ("clock", 96, "Home / New course"),
         ("read", 96, "Classroom lesson"),
         ("cheer", 96, "Check correct"),
         ("think", 96, "Wrong answer"),
         ("sleep", 96, "Empty / offline")]

PROOF = r"""
import React from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import fs from 'node:fs'

const payload = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'))
// The route width has to be set before the module evaluates: the SDK stub's viewport atom reads it
// at import time, and FoxPose is absent below 620.
globalThis.__CB_TEST_WIDTH__ = '1344'
const mod = await import('./plugin.js')

const figure = (row) => React.createElement('figure', { className: 'proof-plate' },
  React.createElement(mod.FoxPose, { pose: row.pose, size: row.size, style: { marginInlineEnd: '0' } }),
  React.createElement('figcaption', null,
    React.createElement('b', null, row.pose + ' @ ' + row.size),
    React.createElement('span', null, row.surface)))

const hero = payload.hero.map((row) => figure({ pose: row[0], size: row[1], surface: row[2] }))
const strip = payload.strip.map((row) => figure({ pose: row[0], size: row[1], surface: row[2] }))

const body = React.createElement('div', { className: 'proof-sheet' },
  React.createElement('h1', null, 'The adopted painted fox'),
  React.createElement('p', { className: 'proof-note' },
    'Generated from desktop/plugin.js. Every plate is the painted A1 export the brand-asset '
    + 'segment ships; the captions are proof chrome, not product chrome.'),
  React.createElement('div', { className: 'proof-row proof-hero' }, ...hero),
  React.createElement('div', { className: 'proof-row proof-strip' }, ...strip))

const markup = renderToStaticMarkup(
  React.createElement(mod.CbV3Scope, {
    mode: 'light',
    className: 'proof-route',
    attributes: { 'data-cb-route': '/coursebook', 'data-cb-scope': 'light', 'data-cb-v3': '' }
  }, body)
)
process.stdout.write(JSON.stringify({ markup }))
"""

PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Coursebook fox — generated proof of the adopted painted set</title>
<style>
  html, body {{ margin: 0; padding: 0; width: 1100px; height: 560px; overflow: hidden; }}
  * {{ box-sizing: border-box; }}
  .proof-route {{ width: 1100px; height: 560px; display: flex; }}
  .proof-sheet {{ width: 100%; padding: 34px 44px; display: flex; flex-direction: column; gap: 18px; }}
  .proof-sheet h1 {{ margin: 0; font-family: var(--cb3-font-display); font-size: 34px; line-height: 1.1; }}
  .proof-note {{ margin: 0; font-family: var(--cb3-font-ui); font-size: 14px; color: var(--cb3-ink-soft); }}
  .proof-row {{ display: flex; align-items: flex-end; gap: 44px; }}
  .proof-plate {{ margin: 0; display: flex; flex-direction: column; align-items: center; gap: 10px; }}
  .proof-plate figcaption {{ display: flex; flex-direction: column; align-items: center; gap: 2px;
    font-family: var(--cb3-font-ui); font-size: 13px; line-height: 1.2; color: var(--cb3-ink); }}
  .proof-plate figcaption span {{ font-size: 11px; color: var(--cb3-ink-soft); }}
  .proof-strip {{ margin-top: auto; gap: 26px; }}
</style>
</head>
<body>
<!-- Generated by scripts/gen-fox-proof.py from desktop/plugin.js (sha256 {sha}). Do not hand-edit:
     tests/test_cp010_fox_assets.py regenerates this page and fails on any difference. -->
<script>
  // This page is generated from desktop/plugin.js, and the committed bytes are pinned to a fresh
  // render of it by tests/test_cp010_fox_assets.py, so the module sha below is measured, not
  // asserted: it is the sha256 the generator read out of the file it rendered this markup from.
  // scripts/cp-capture.mjs --fixture reads it through window.__CP000_FIXTURE__.
  window.__CP000_FIXTURE__ = {{ plugin: {{ window_sha256: '{sha}' }} }};
</script>
{markup}
</body>
</html>
"""


def _node_modules() -> Path:
    candidates = [
        os.environ.get("HERMES_DESKTOP_APP"),
        str(Path.home() / ".hermes" / "hermes-agent" / "apps" / "desktop"),
        str(Path.home() / ".hermes" / "hermes-agent"),
    ]
    for candidate in candidates:
        if not candidate:
            continue
        modules = Path(candidate) / "node_modules"
        if (modules / "react").is_dir() and (modules / "react-dom" / "server.js").is_file():
            return modules
    raise SystemExit("react/react-dom are not installed beside the desktop app")


def render(out: Path) -> str:
    sys.path.insert(0, str(ROOT))
    from tests.test_desktop_lesson_views import SDK_STUB  # the same stub the render suites use

    modules = _node_modules()
    module_sha = hashlib.sha256(PLUGIN_JS.read_bytes()).hexdigest()
    with tempfile.TemporaryDirectory(prefix="coursebook-fox-proof-") as tmp:
        root = Path(tmp)
        (root / "plugin.js").write_text(PLUGIN_JS.read_text(encoding="utf-8"), encoding="utf-8")
        (root / "render.mjs").write_text(PROOF, encoding="utf-8")
        node_modules = root / "node_modules"
        node_modules.mkdir()
        for name in ("react", "react-dom", "scheduler"):
            source = modules / name
            if source.is_dir():
                (node_modules / name).symlink_to(source, target_is_directory=True)
        sdk = node_modules / "@hermes" / "plugin-sdk"
        sdk.mkdir(parents=True)
        (sdk / "package.json").write_text(
            json.dumps({"name": "@hermes/plugin-sdk", "type": "module", "main": "index.js"}),
            encoding="utf-8",
        )
        (sdk / "index.js").write_text(SDK_STUB, encoding="utf-8")

        case = root / "case.json"
        case.write_text(json.dumps({"hero": HERO, "strip": STRIP}), encoding="utf-8")
        result = subprocess.run(
            ["node", str(root / "render.mjs"), str(case)],
            cwd=root, capture_output=True, text=True, timeout=300,
        )
        if result.returncode != 0:
            raise SystemExit(result.stderr[-4000:])
        markup = json.loads(result.stdout)["markup"]

    page = PAGE.format(sha=module_sha, markup=markup)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(page, encoding="utf-8")
    return module_sha


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    parser.add_argument("--check", action="store_true", help="fail when the committed page is stale")
    args = parser.parse_args()
    out = Path(args.out)
    if args.check:
        with tempfile.TemporaryDirectory(prefix="coursebook-fox-check-") as tmp:
            fresh = Path(tmp) / "fox-adoption.html"
            render(fresh)
            if not out.exists() or out.read_bytes() != fresh.read_bytes():
                print(f"{out} is stale: regenerate with scripts/gen-fox-proof.py", file=sys.stderr)
                return 1
        print(f"{out} matches a fresh render of desktop/plugin.js")
        return 0
    sha = render(out)
    print(f"wrote {out} from desktop/plugin.js sha256 {sha}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
