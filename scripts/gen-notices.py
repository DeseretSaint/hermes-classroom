#!/usr/bin/env python3
"""Generate ``docs/launch/NOTICES.md`` from the committed asset manifests.

Why this exists
---------------
Coursebook ships third-party typefaces and brand assets, and a notices list typed by hand is how
unverified placeholder rows ("SIL OFL 1.1", "CC BY 4.0") reach a launch surface. This script reads
every ``assets/**/manifest.json`` row and emits exactly one notices row per manifest row, with the
licence id the manifest declares, where that licence's text can be read, and whether the licence
id permits commercial use. It never invents a licence id: a row whose licence is missing is emitted
as ``UNKNOWN``, and a row whose id is not in :data:`LICENCE_REGISTRY` keeps the declared id but is
marked unresolved — ``UNKNOWN`` commercial use, and the reason in its evidence cell — so the gap
stays visible instead of being rounded to a permissive answer.

Usage
-----
    python3 scripts/gen-notices.py            # write docs/launch/NOTICES.md
    python3 scripts/gen-notices.py --check    # verify only; exit 1 when the committed file has drifted

Exit codes: 0 written / byte-identical; 1 ``--check`` found drift; 2 the inputs are not readable or
not internally consistent (duplicate asset id, manifest row without a provenance id, no manifests).

Determinism
-----------
No timestamps and no host state. The header pins the sha256 of every manifest it read, so adding a
manifest row changes the generated bytes and ``--check`` fails until the file is regenerated.
Documented in ``docs/launch/NOTICES.md`` itself: the row set is the manifest row set.
"""

from __future__ import annotations

import hashlib
import json
import sys
from dataclasses import dataclass
from difflib import unified_diff
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTICES = ROOT / "docs" / "launch" / "NOTICES.md"
ASSETS = "assets"


@dataclass(frozen=True)
class Licence:
    """A licence id this inventory is willing to classify, with the text that backs it."""

    identifier: str
    commercial_use: str  # "Yes" | "No"
    basis: str
    text_url: str


# The registry is the only place a licence id becomes a commercial-use answer. Adding a licence to a
# manifest without adding it here makes the row UNKNOWN on purpose: the inventory may not guess that
# an unfamiliar id is permissive.
LICENCE_REGISTRY: dict[str, Licence] = {
    "CC0-1.0": Licence(
        identifier="CC0-1.0",
        commercial_use="Yes",
        basis=(
            "CC0 1.0 Universal public-domain dedication; the affirmer waives copyright and "
            "neighbouring rights, so commercial use is permitted without attribution."
        ),
        text_url="https://creativecommons.org/publicdomain/zero/1.0/legalcode.en",
    ),
    "OFL-1.1": Licence(
        identifier="OFL-1.1",
        commercial_use="Yes",
        basis=(
            "SIL Open Font License 1.1 permits use, modification and redistribution, including "
            "commercial use; a Reserved Font Name may not be reused by a modified version and the "
            "copyright notice and licence must travel with the font."
        ),
        text_url="https://openfontlicense.org/open-font-license-official-text/",
    ),
}

# A declared licence file is only evidence when its own text names the licence the manifest claims.
# This is the check that stops a copied "OFL" filename from standing in for an actual OFL text.
LICENCE_TEXT_MARKERS: dict[str, str] = {
    "OFL-1.1": "SIL OPEN FONT LICENSE Version 1.1",
}

UNKNOWN = "UNKNOWN"


class InventoryError(Exception):
    """The manifests cannot be turned into an honest inventory."""


@dataclass(frozen=True)
class SourceRow:
    asset_id: str
    kind: str
    licence: str
    evidence: str
    commercial_use: str
    manifest: str
    resolved: bool


def _manifest_rows(data: object) -> list[dict]:
    """Every manifest shape in ``assets/``: a top-level list, or a dict whose rows live in ``tiles``."""
    if isinstance(data, list):
        return [row for row in data if isinstance(row, dict)]
    if isinstance(data, dict):
        for key in ("tiles", "entries", "items", "files"):
            rows = data.get(key)
            if isinstance(rows, list):
                return [row for row in rows if isinstance(row, dict)]
    raise InventoryError("manifest is neither a row list nor a dict with a row list")


def manifest_paths(root: Path) -> list[Path]:
    """Every manifest under ``assets/``, sorted. Nested manifests count: material lives in art/."""
    base = root / ASSETS
    if not base.is_dir():
        raise InventoryError("no assets/ directory under %s" % root)
    paths = sorted(p for p in base.rglob("manifest.json") if p.is_file())
    if not paths:
        raise InventoryError("no manifest.json files under %s" % base)
    return paths


def _resolve_licence(root: Path, row: dict, licence: str) -> tuple[str, str, bool]:
    """Return (evidence, commercial_use, resolved) for one manifest row."""
    declared = row.get("licence")
    if not isinstance(declared, str) or not declared.strip():
        return ("%s: manifest row declares no licence" % UNKNOWN, UNKNOWN, False)
    licence = declared.strip()

    licence_file = row.get("licence_file")
    if isinstance(licence_file, str) and licence_file.strip():
        rel = licence_file.strip()
        path = root / rel
        if not path.is_file():
            return ("%s: declared `%s` is not committed" % (UNKNOWN, rel), UNKNOWN, False)
        marker = LICENCE_TEXT_MARKERS.get(licence)
        if marker is not None:
            text = path.read_text(encoding="utf-8", errors="replace")
            if marker not in text:
                return (
                    "%s: `%s` does not contain %r" % (UNKNOWN, rel, marker),
                    UNKNOWN,
                    False,
                )
        known = LICENCE_REGISTRY.get(licence)
        if known is None:
            return (
                "`%s` (%s: licence id `%s` is not in the generator registry)" % (rel, UNKNOWN, licence),
                UNKNOWN,
                False,
            )
        return ("`%s`" % rel, known.commercial_use, True)

    known = LICENCE_REGISTRY.get(licence)
    if known is None:
        return (
            "%s: licence id `%s` is not in the generator registry" % (UNKNOWN, licence),
            UNKNOWN,
            False,
        )
    return ("<%s>" % known.text_url, known.commercial_use, True)


def collect_rows(root: Path = ROOT) -> list[SourceRow]:
    """Read every manifest row into one notices row. Raises InventoryError on inconsistent input."""
    rows: list[SourceRow] = []
    seen: dict[str, str] = {}
    for path in manifest_paths(root):
        rel_manifest = path.relative_to(root).as_posix()
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise InventoryError("%s is not JSON: %s" % (rel_manifest, exc)) from exc
        manifest_rows = _manifest_rows(data)
        if not manifest_rows:
            raise InventoryError("%s carries no rows" % rel_manifest)
        for index, row in enumerate(manifest_rows):
            asset_id = row.get("provenance_id")
            if not isinstance(asset_id, str) or not asset_id.strip():
                raise InventoryError(
                    "%s row %d has no provenance_id; a notices row cannot be keyed" % (rel_manifest, index)
                )
            asset_id = asset_id.strip()
            if asset_id in seen:
                raise InventoryError(
                    "duplicate asset id %r in %s and %s" % (asset_id, seen[asset_id], rel_manifest)
                )
            seen[asset_id] = rel_manifest
            licence = row.get("licence")
            licence_id = licence.strip() if isinstance(licence, str) and licence.strip() else UNKNOWN
            evidence, commercial, resolved = _resolve_licence(root, row, licence_id)
            kind = row.get("kind") or row.get("role") or "asset"
            rows.append(
                SourceRow(
                    asset_id=asset_id,
                    kind=str(kind),
                    licence=licence_id,
                    evidence=evidence,
                    commercial_use=commercial,
                    manifest=rel_manifest,
                    resolved=resolved,
                )
            )
    rows.sort(key=lambda row: (row.asset_id, row.manifest))
    return rows


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def render(root: Path = ROOT) -> str:
    """Render NOTICES.md. Deterministic: same manifests in, same bytes out."""
    rows = collect_rows(root)
    inputs = []
    for path in manifest_paths(root):
        rel = path.relative_to(root).as_posix()
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        count = sum(1 for row in rows if row.manifest == rel)
        inputs.append((rel, count, digest))

    licence_counts: dict[str, int] = {}
    commercial_counts: dict[str, int] = {}
    for row in rows:
        licence_counts[row.licence] = licence_counts.get(row.licence, 0) + 1
        commercial_counts[row.commercial_use] = commercial_counts.get(row.commercial_use, 0) + 1
    unresolved = sum(1 for row in rows if not row.resolved)

    lines: list[str] = [
        "<!-- generated by scripts/gen-notices.py; do not edit by hand -->",
        "",
        "# Third-party asset notices",
        "",
        "Coursebook ships third-party typefaces and brand assets. This file is their machine-generated",
        "licence inventory: one row per committed manifest row, with the licence id the manifest",
        "declares, where that licence's text can be read, and whether the licence id permits",
        "commercial use. `docs/launch/CREDITS.md` is the walkthrough video's film credits, not this",
        "inventory.",
        "",
        "## Generated from",
        "",
        "| Input manifest | Rows | sha256 |",
        "| --- | ---: | --- |",
    ]
    for rel, count, digest in inputs:
        lines.append("| `%s` | %d | `%s` |" % (rel, count, digest))
    lines += [
        "",
        "%d manifests, %d asset sources." % (len(inputs), len(rows)),
        "",
        "## Licence registry",
        "",
        "| Licence id | Permits commercial use | Basis |",
        "| --- | --- | --- |",
    ]
    for licence in sorted(LICENCE_REGISTRY.values(), key=lambda item: item.identifier):
        lines.append(
            "| `%s` | %s | %s Text: <%s> |"
            % (
                licence.identifier,
                licence.commercial_use,
                _cell(licence.basis),
                licence.text_url,
            )
        )
    lines += [
        "",
        "The registry above is the only place a licence id becomes a commercial-use answer. A row",
    ]
    if unresolved:
        lines += [
            "whose licence is missing, or whose id is not in the registry, is reported as `%s` with"
            % UNKNOWN,
            "the reason in its evidence cell rather than guessed.",
        ]
    else:
        lines += [
            "whose licence is missing, or whose id is not in the registry, would be reported",
            "explicitly with the reason in its evidence cell rather than guessed; every licence id",
            "below is in this registry.",
        ]
    lines += [
        "Commercial use here is a classification of the licence id, not a legal opinion about a",
        "particular asset.",
        "",
        "## Asset inventory",
        "",
        "| Asset id | Kind | Licence | Licence file or URL | Commercial use |",
        "| --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        lines.append(
            "| `%s` | %s | `%s` | %s | %s |"
            % (
                _cell(row.asset_id),
                _cell(row.kind),
                _cell(row.licence),
                row.evidence,
                row.commercial_use,
            )
        )

    counts = ", ".join("%s %d" % (key, licence_counts[key]) for key in sorted(licence_counts))
    commercial = ", ".join(
        "%s %d" % (key, commercial_counts[key]) for key in sorted(commercial_counts)
    )
    lines += [
        "",
        "## Summary",
        "",
        "- asset sources: %d" % len(rows),
        "- licence ids: %s" % counts,
        "- commercial use: %s" % commercial,
        "- rows with an unresolved licence: %d" % unresolved,
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    check = "--check" in argv[1:]
    unknown_args = [arg for arg in argv[1:] if arg != "--check"]
    if unknown_args:
        print("usage: gen-notices.py [--check]", file=sys.stderr)
        return 2
    try:
        rendered = render(ROOT)
        rows = collect_rows(ROOT)
    except InventoryError as exc:
        print("gen-notices: %s" % exc, file=sys.stderr)
        return 2

    if check:
        if not NOTICES.is_file():
            print("gen-notices: %s does not exist; run without --check" % NOTICES.relative_to(ROOT))
            return 1
        committed = NOTICES.read_text(encoding="utf-8")
        if committed == rendered:
            print(
                "NOTICES.md is up to date: 0 diff lines (%d rows, %d unresolved)"
                % (len(rows), sum(1 for row in rows if not row.resolved))
            )
            return 0
        diff = list(
            unified_diff(
                committed.splitlines(keepends=True),
                rendered.splitlines(keepends=True),
                fromfile="committed/docs/launch/NOTICES.md",
                tofile="generated/docs/launch/NOTICES.md",
            )
        )
        sys.stdout.writelines(diff)
        print(
            "gen-notices: drift: %d diff lines; regenerate with `python3 scripts/gen-notices.py`"
            % len(diff),
            file=sys.stderr,
        )
        return 1

    NOTICES.parent.mkdir(parents=True, exist_ok=True)
    NOTICES.write_text(rendered, encoding="utf-8")
    print(
        "wrote %s: %d rows, %d unresolved"
        % (NOTICES.relative_to(ROOT), len(rows), sum(1 for row in rows if not row.resolved))
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
