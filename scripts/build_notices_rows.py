#!/usr/bin/env python3
"""Regenerate the notice rows in ``desktop/src/31-notices.js``.

The in-app Third-party notices surface must render exactly the rows in
``docs/launch/NOTICES.md``. Those rows are themselves generated by
``scripts/gen-notices.py`` from the committed asset manifests, so typing a licence id into the
Desktop module by hand is how a notice becomes a lie. This script reads the same
:func:`collect_rows` data and rewrites the marked ``CB_NOTICE_ROWS`` literal in the segment:

    python3 scripts/build_notices_rows.py           # rewrite the generated rows
    python3 scripts/build_notices_rows.py --check   # exit 1 when they have drifted

``tests/test_desktop_notices.py`` recomputes the same bytes, so a hand edit of the marked block
fails there too. The component around the block is hand-written; only the data inside the markers
is generated.

Exit codes: 0 written / already current; 1 ``--check`` found drift; 2 the markers are missing or
the manifests cannot be read.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import re
import sys
from dataclasses import asdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GENERATOR = ROOT / "scripts" / "gen-notices.py"
SEGMENT = ROOT / "desktop" / "src" / "31-notices.js"

BEGIN = "// BEGIN GENERATED NOTICE ROWS"
END = "// END GENERATED NOTICE ROWS"
BLOCK_RE = re.compile(
    r"// BEGIN GENERATED NOTICE ROWS[^\n]*\n.*?// END GENERATED NOTICE ROWS\n",
    re.S,
)


def _load_generator():
    """Load ``gen-notices.py`` without requiring ``scripts`` to be a package."""
    spec = importlib.util.spec_from_file_location("cb_gen_notices_for_rows", GENERATOR)
    if spec is None or spec.loader is None:  # pragma: no cover - a missing script is fatal
        raise SystemExit("build_notices_rows: scripts/gen-notices.py is missing")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def rows_payload(root: Path = ROOT) -> list[dict]:
    """The generator's rows, in its own order, as plain JSON-ready dicts."""
    generator = _load_generator()
    try:
        rows = generator.collect_rows(root)
    except generator.InventoryError as exc:
        raise SystemExit("build_notices_rows: %s" % exc)
    return [asdict(row) for row in rows]


def rendered_block(rows: list[dict]) -> str:
    """The exact marked block, deterministic for a fixed manifest tree."""
    body = json.dumps(rows, ensure_ascii=True, indent=2)
    return (
        BEGIN
        + "\n// Written by scripts/build_notices_rows.py from the same rows as docs/launch/NOTICES.md.\n"
        + "// Do not edit by hand: a licence id typed here is a licence id nobody verified.\n"
        + "const CB_NOTICE_ROWS = Object.freeze(%s)\n" % body
        + END
        + "\n"
    )


def apply(source: str, rows: list[dict]) -> str:
    """Replace the marked block in ``source``; refuse a segment that lost its markers."""
    if BLOCK_RE.search(source) is None:
        raise SystemExit("build_notices_rows: the generated rows are not marked in 31-notices.js")
    return BLOCK_RE.sub(lambda _: rendered_block(rows), source, count=1)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--root", default=str(ROOT), help="checkout to build (default: this repo)")
    parser.add_argument("--check", action="store_true", help="verify only; exit 1 on drift")
    args = parser.parse_args(argv)

    root = Path(args.root).resolve()
    segment = root / "desktop" / "src" / "31-notices.js"
    if not segment.is_file():
        print("build_notices_rows: %s is missing" % segment.relative_to(root), file=sys.stderr)
        return 2

    rows = rows_payload(root)
    current = segment.read_text(encoding="utf-8")
    expected = apply(current, rows)

    if args.check:
        if current != expected:
            print(
                "build_notices_rows: desktop/src/31-notices.js does not carry the generated "
                "rows; run `python3 scripts/build_notices_rows.py`",
                file=sys.stderr,
            )
            return 1
        print(
            "build_notices_rows: 31-notices.js matches the generator (%d rows)" % len(rows)
        )
        return 0

    if current != expected:
        segment.write_text(expected, encoding="utf-8")
        print(
            "build_notices_rows: wrote %d rows into desktop/src/31-notices.js" % len(rows)
        )
    else:
        print("build_notices_rows: rows already match (%d rows)" % len(rows))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
