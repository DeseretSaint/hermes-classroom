#!/usr/bin/env python3
"""Render the shipped wide Home scene to a standalone parity proof page.

CP-053's binding reference is `docs/concept-parity/refs/home.png` (R-HOME, 1344x768). The proof
page is **generated from `desktop/plugin.js`**, not authored: it mounts the same `CoursebookHome`
at route width 1344 inside the same `CbV3Scope` the route uses, so the shipped stylesheet, token
variables, material tiles and markup are the ones photographed. `tests/test_desktop_home_scene_
parity.py` re-runs this generator and fails when the committed page differs from a fresh render.

What the proof is not: a Desktop capture. There is no host, no backend and no chat rail, so the
frame shows the scene canvas only (the app header and window chrome are outside this file) and a
card with no host media read paints the product's own typographic cover fallback.

Usage:
  python3 scripts/gen-home-proof.py [--out design/home-scene.html] [--check]
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLUGIN_JS = ROOT / "desktop" / "plugin.js"
DEFAULT_OUT = ROOT / "design" / "home-scene.html"

# The reference's four titles, with the two typos corrected, and the section pairs CP-005 carries.
# The order is the reference's left-to-right order; the shelf sorts by newest write, so the stamps
# descend in that same order.
ROWS = [
    {"title": "Auto Repair Fundamentals", "sections_total": 8, "sections_done": 5,
     "updated_at": "2026-11-10T09:00:00.000000+00:00"},
    {"title": "Japanese Cafe Basics", "sections_total": 4, "sections_done": 2,
     "updated_at": "2026-11-09T09:00:00.000000+00:00"},
    {"title": "Astronomy", "sections_total": 6, "sections_done": 1,
     "updated_at": "2026-11-08T09:00:00.000000+00:00"},
    {"title": "Sourdough", "sections_total": 3, "sections_done": 0,
     "updated_at": "2026-11-07T09:00:00.000000+00:00"},
]

PROOF = r"""
import React from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import fs from 'node:fs'

const payload = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'))
// The route width has to be set before the module evaluates: the SDK stub's viewport atom reads it
// at import time, and the scene is the `route >= 1200` branch.
globalThis.__CB_TEST_WIDTH__ = '1344'
const mod = await import('./plugin.js')

const rows = payload.rows.map((row, index) => ({
  enrollment_id: `enr_${String(index).padStart(16, '0')}`,
  course_id: `crs_${String(index).padStart(16, '0')}`,
  title: row.title,
  subtitle: null,
  recipe: 'committed',
  level_label: null,
  locale: null,
  learner_label: null,
  enrollment_status: 'active',
  course_status: 'active',
  provenance: { source: 'authored', pack_id: null, pack_version: null },
  next_step: { kind: 'resume_lesson', label: 'Resume this lesson' },
  evidence_summary: { independent: 0, review_due: 0, total_objectives: 4, current_objective_id: 'obj' },
  warning: null,
  updated_at: row.updated_at,
  revision: 0,
  sections_total: row.sections_total,
  sections_done: row.sections_done
}))

const home = React.createElement(mod.CoursebookHome, {
  library: {
    status: 'ready',
    data: { items: rows, next_cursor: null, total: rows.length, empty_reason: null, applied_filter: 'all' },
    error: null,
    stale: false
  },
  modes: {},
  modesSupported: true,
  online: true,
  canCreate: true,
  onStartCreate: () => {},
  onBrowseLibrary: () => {},
  onOpenCourse: () => {},
  onShowAll: () => {},
  onOpenStudio: () => {},
  onRetry: () => {}
})

const markup = renderToStaticMarkup(
  React.createElement(mod.CbV3Scope, {
    mode: 'light',
    className: 'relative flex h-full min-h-0 flex-col',
    attributes: { 'data-cb-route': '/coursebook', 'data-cb-scope': 'light' }
  }, home)
)
process.stdout.write(JSON.stringify({ markup }))
"""

PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Coursebook Home — generated proof of the shipped scene (1344x768)</title>
<style>
  html, body {{ margin: 0; padding: 0; width: 1344px; height: 768px; overflow: hidden; }}
  * {{ box-sizing: border-box; }}
</style>
</head>
<body>
<!-- Generated by scripts/gen-home-proof.py from desktop/plugin.js (sha256 {sha}). Do not hand-edit:
     tests/test_desktop_home_scene_parity.py regenerates this page and fails on any difference. -->
{markup}
</body>
</html>
"""


def _node_modules() -> Path:
    candidates = [
        os.environ.get("HERMES_DESKTOP_APP"),
        str(Path.home() / ".hermes" / "hermes-agent" / "apps" / "desktop"),
        str(Path.home() / ".hermes" / "hermes-agent"),
    ]
    for candidate in candidates:
        if not candidate:
            continue
        modules = Path(candidate) / "node_modules"
        if (modules / "react").is_dir() and (modules / "react-dom" / "server.js").is_file():
            return modules
    raise SystemExit("react/react-dom are not installed beside the desktop app")


def render(out: Path) -> str:
    sys.path.insert(0, str(ROOT))
    from tests.test_desktop_lesson_views import SDK_STUB  # the same stub the render suites use

    modules = _node_modules()
    module_sha = __import__("hashlib").sha256(PLUGIN_JS.read_bytes()).hexdigest()
    with tempfile.TemporaryDirectory(prefix="coursebook-cp053-proof-") as tmp:
        root = Path(tmp)
        (root / "plugin.js").write_text(PLUGIN_JS.read_text(encoding="utf-8"), encoding="utf-8")
        (root / "render.mjs").write_text(PROOF, encoding="utf-8")
        node_modules = root / "node_modules"
        node_modules.mkdir()
        for name in ("react", "react-dom", "scheduler"):
            source = modules / name
            if source.is_dir():
                (node_modules / name).symlink_to(source, target_is_directory=True)
        sdk = node_modules / "@hermes" / "plugin-sdk"
        sdk.mkdir(parents=True)
        (sdk / "package.json").write_text(
            json.dumps({"name": "@hermes/plugin-sdk", "type": "module", "main": "index.js"}), encoding="utf-8"
        )
        (sdk / "index.js").write_text(SDK_STUB, encoding="utf-8")

        case = root / "case.json"
        case.write_text(json.dumps({"rows": ROWS}), encoding="utf-8")
        result = subprocess.run(
            ["node", str(root / "render.mjs"), str(case)],
            cwd=root, capture_output=True, text=True, timeout=300,
        )
        if result.returncode != 0:
            raise SystemExit(result.stderr[-4000:])
        markup = json.loads(result.stdout)["markup"]

    page = PAGE.format(sha=module_sha, markup=markup)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(page, encoding="utf-8")
    return module_sha


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    parser.add_argument("--check", action="store_true", help="fail when the committed page is stale")
    args = parser.parse_args()
    out = Path(args.out)
    if args.check:
        with tempfile.TemporaryDirectory(prefix="coursebook-cp053-check-") as tmp:
            fresh = Path(tmp) / "home-scene.html"
            render(fresh)
            if not out.exists() or out.read_bytes() != fresh.read_bytes():
                print(f"{out} is stale: regenerate with scripts/gen-home-proof.py", file=sys.stderr)
                return 1
        print(f"{out} matches a fresh render of desktop/plugin.js")
        return 0
    sha = render(out)
    print(f"wrote {out} from desktop/plugin.js sha256 {sha}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
