#!/usr/bin/env python3
"""Generate the UI context pack from the design reference.

Reads design/home-scene.html (optionally from a git revision), extracts the
declarations the manager is allowed to rely on, and writes a Markdown pack with
the source commit and a content hash. Hand-written geometry is forbidden.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_REF = "design/home-scene.html"
DEFAULT_REV = "wt/cp-053-home-scene"

# Selectors whose box or type the manager may quote. Values are read from the
# stylesheet, never typed here.
BOX_SELECTORS = [
    "header", ".brand", "nav", ".studio", ".hero", ".hero h1", ".hero p",
    ".shelf.cards", ".card", ".card .cover", ".plank.one", ".plank.two",
    ".tag", ".clock", ".fox", ".bracket",
]
TYPE_SELECTORS = [
    ".brand", "nav a", ".studio", ".hero h1", ".hero p", ".btn", ".card h3",
    ".tag",
]


def read_reference(rev: str, path: str) -> tuple[str, str]:
    try:
        out = subprocess.run(
            ["git", "show", f"{rev}:{path}"],
            cwd=ROOT, capture_output=True, text=True, check=True,
        )
        commit = subprocess.run(
            ["git", "rev-parse", rev], cwd=ROOT, capture_output=True,
            text=True, check=True,
        ).stdout.strip()
        return out.stdout, commit
    except subprocess.CalledProcessError:
        p = ROOT / path
        if not p.exists():
            sys.exit(f"no reference at {rev}:{path} and no working-tree copy")
        return p.read_text(), "working-tree"


def parse_rules(css: str) -> dict[str, dict[str, str]]:
    rules: dict[str, dict[str, str]] = {}
    for m in re.finditer(r"([^{}]+)\{([^{}]*)\}", css):
        selectors = [s.strip() for s in m.group(1).split(",")]
        decls = {}
        for part in m.group(2).split(";"):
            if ":" in part:
                k, v = part.split(":", 1)
                decls[k.strip()] = v.strip()
        for sel in selectors:
            if sel:
                rules.setdefault(sel, {}).update(decls)
    return rules


def box(rule: dict[str, str]) -> str:
    keys = ("left", "top", "right", "width", "height")
    vals = [f"{k} {rule[k]}" for k in keys if k in rule]
    return ", ".join(vals) if vals else "—"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rev", default=DEFAULT_REV)
    ap.add_argument("--path", default=DEFAULT_REF)
    ap.add_argument("--out", default="docs/launch/UI-CONTEXT-PACK.generated.md")
    args = ap.parse_args()

    html, commit = read_reference(args.rev, args.path)
    css = "\n".join(re.findall(r"<style>(.*?)</style>", html, re.S))
    rules = parse_rules(css)
    digest = hashlib.sha256(html.encode()).hexdigest()[:16]

    assets = re.findall(r'src="([^"]+)"', html)
    type_rows, off_scale = [], []
    # Fixed steps only. Heading and display must use their clamp tokens, so a
    # fixed px value in that range is still off-scale.
    scale = {12, 14, 16, 20}
    for sel in TYPE_SELECTORS:
        r = rules.get(sel, {})
        size = r.get("font-size")
        if not size:
            continue
        px = re.match(r"(\d+)px$", size)
        flag = ""
        if px and int(px.group(1)) not in scale:
            flag = "off-scale"
            off_scale.append(f"{sel} {size}")
        type_rows.append(
            f"| `{sel}` | {size} | {r.get('line-height', '—')} | "
            f"{r.get('font-weight', '—')} | {r.get('font-family', '—')} | {flag} |"
        )

    lines = [
        "# UI context pack — generated",
        "",
        f"Source: `{args.path}` at `{commit}`  ",
        f"Content hash: `{digest}`  ",
        "Do not edit this file. Regenerate with `python3 scripts/gen-ui-pack.py`.",
        "",
        "## Geometry",
        "",
        "| selector | box |",
        "|---|---|",
    ]
    for sel in BOX_SELECTORS:
        r = rules.get(sel)
        if r:
            lines.append(f"| `{sel}` | {box(r)} |")
    lines += [
        "",
        "## Type inventory",
        "",
        "| selector | size | line-height | weight | family | flag |",
        "|---|---|---|---|---|---|",
        *type_rows,
        "",
        "Off-scale roles: " + (", ".join(off_scale) if off_scale else "none"),
        "",
        "## Assets",
        "",
        *[f"- `{a}`" for a in dict.fromkeys(assets)],
        "",
        "## Rule",
        "",
        "Every geometry, type or asset number a card quotes must appear in this file. If it is not",
        "here, it is not a requirement.",
        "",
    ]
    out = ROOT / args.out
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({len(lines)} lines), source {commit}, hash {digest}")
    print("off-scale:", ", ".join(off_scale) or "none")


if __name__ == "__main__":
    main()
