#!/usr/bin/env python3
"""CP-012 cover contact sheet: the labelled review artifact for owner approval.

Every label is drawn by Pillow from the file list and the machine record — never
by the model, and never shipped as product UI. This is a review artifact.

Usage: python3 scripts/cp012-contact-sheet.py
Writes docs/concept-parity/covers/cover-contact-sheet.png
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
COVERS = ROOT / "assets" / "art" / "covers"
AUDIT = ROOT / "audit" / "cp012-covers"
OUT = ROOT / "docs" / "concept-parity" / "covers" / "cover-contact-sheet.png"

PAPER = (247, 241, 228)
INK = (26, 23, 19)
SOFT = (92, 83, 71)
RULE = (215, 203, 180)
LAMP = (183, 100, 61)
FONT = "/usr/share/fonts/liberation/LiberationSans-%s.ttf"

SLUGS = {
    "japanese-affection-context-l0": "japanese",
    "parent-measurement-practice": "parent",
    "technical-demo-pack": "technical",
}


def font(size: int, bold: bool = False) -> ImageFont.FreeTypeFont:
    return ImageFont.truetype(FONT % ("Bold" if bold else "Regular"), size)


def sha16(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16]


def wrap(d: ImageDraw.ImageDraw, text: str, face: ImageFont.FreeTypeFont, max_w: int) -> list[str]:
    lines: list[str] = []
    current = ""
    for word in text.split():
        probe = f"{current} {word}".strip()
        if d.textlength(probe, font=face) <= max_w or not current:
            current = probe
        else:
            lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines


def main() -> int:
    swap = {c["pack"]: c for c in json.loads((AUDIT / "swap-check.json").read_text())["covers"]}
    prov = json.loads((AUDIT / "provenance.json").read_text())

    cell_w, cell_h = 430, 560
    cols = 3
    head, foot = 170, 250
    width = cols * cell_w + 64
    height = head + cell_h + foot
    im = Image.new("RGB", (width, height), PAPER)
    d = ImageDraw.Draw(im)

    d.text((32, 26), "A3 workshop pack covers — contact sheet", font=font(34, True), fill=INK)
    d.text((32, 76),
           "One cover kit: one paper, one line, one upper-left light. Textless plates; every word "
           "on the shelf is DOM text.",
           font=font(18), fill=SOFT)
    d.text((32, 104),
           "Masters 1200x800 (3:2); the 4:5 file is a mechanical centre crop. Drawn for the three "
           "bundled packs only.",
           font=font(18), fill=SOFT)
    d.text((32, 132),
           "Owner approval: ____________________   (unsigned — this sheet is submitted, not approved)",
           font=font(18, True), fill=LAMP)
    d.line([(32, 164), (width - 32, 164)], fill=RULE, width=1)

    for i, (pack, slug) in enumerate(SLUGS.items()):
        cx = 32 + i * cell_w
        cy = head
        master = COVERS / f"{slug}-master-1200x800.png"
        crop45 = COVERS / f"{slug}-crop-4x5-640x800.png"

        art = Image.open(master).convert("RGB")
        art.thumbnail((380, 254), Image.LANCZOS)
        im.paste(art, (cx + 10, cy))

        card = Image.open(master).convert("RGB")
        card.thumbnail((240, 160), Image.LANCZOS)
        im.paste(card, (cx + 10, cy + 272))
        d.rectangle([cx + 10, cy + 272, cx + 10 + card.width, cy + 272 + card.height],
                    outline=RULE, width=1)
        d.text((cx + 16, cy + 438), "240 px card", font=font(13), fill=SOFT)

        portrait = Image.open(crop45).convert("RGB")
        portrait.thumbnail((120, 150), Image.LANCZOS)
        im.paste(portrait, (cx + 270, cy + 272))
        d.text((cx + 270, cy + 428), "4:5 crop", font=font(13), fill=SOFT)

        row = swap[pack]
        y = cy + 462
        title_face = font(16, True)
        for n, line in enumerate(wrap(d, row["title"], title_face, cell_w - 40)):
            d.text((cx + 8, y + n * 20), line, font=title_face, fill=INK)
        y += 42
        d.text((cx + 8, y), pack, font=font(13), fill=SOFT)
        d.text((cx + 8, y + 18), f"grammar {row['grammar']} · accent {row['accent']}",
               font=font(13), fill=SOFT)
        motifs = ", ".join(m["mark"] for m in row["motifs"])
        d.text((cx + 8, y + 36), f"motifs: {motifs}", font=font(13), fill=SOFT)
        shipped = next(r for r in prov["rows"] if r["pack"] == pack)["shipped"][0]
        d.text((cx + 8, y + 54), f"master sha256 {shipped['sha256'][:16]}  "
                                 f"{shipped['bytes']} B", font=font(13), fill=SOFT)

    d.line([(32, height - 46), (width - 32, height - 46)], fill=RULE, width=1)
    d.text((32, height - 36),
           "Review artifact, not product UI. Plates generated by the host image tool; provenance "
           "rows in docs/concept-parity/COVERS.md.",
           font=font(13), fill=SOFT)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    im.save(OUT, optimize=True)
    print(f"wrote {OUT.relative_to(ROOT)} ({im.width}x{im.height}, {OUT.stat().st_size} B)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
