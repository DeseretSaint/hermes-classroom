"""The launch notices inventory: every manifest row has one notices row, and no licence is guessed.

``docs/launch/NOTICES.md`` is generated by ``scripts/gen-notices.py`` from the committed asset
manifests. This module holds the four things the card requires:

* the committed file is byte-identical to what the generator produces, and ``--check`` exits 0;
* every row of every ``assets/**/manifest.json`` has exactly one notices row, and no row exists
  for an asset id the manifests do not carry;
* adding a manifest row without regenerating the notices file is detected as drift (the test
  fixture below proves the failure path, not just the happy one);
* an unfamiliar or missing licence id becomes ``UNKNOWN`` with a reason in the evidence cell and
  ``UNKNOWN`` commercial use, never a plausible-looking default.

What this does NOT prove: that a licence grant is valid, or that a CC0 dedication covers a
particular painted asset. The manifests declare the licence id; this inventory reports the
declaration and where the licence text can be read. Legal review is separate.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import sys
import tempfile
import unittest
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GENERATOR = ROOT / "scripts" / "gen-notices.py"
NOTICES = ROOT / "docs" / "launch" / "NOTICES.md"


def _load_generator():
    spec = importlib.util.spec_from_file_location("gen_notices_inventory", GENERATOR)
    assert spec is not None and spec.loader is not None, GENERATOR
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


GEN = _load_generator()


def _plain(cell: str) -> str:
    return cell.strip().strip("`").strip()


def _parse_table(text: str, heading: str) -> list[dict[str, str]]:
    """Parse the first markdown table after ``heading`` into dicts, refusing a malformed table."""
    lines = text.splitlines()
    try:
        start = lines.index(heading)
    except ValueError:  # pragma: no cover - a missing heading is a hard failure below
        raise AssertionError("NOTICES.md has no %r heading" % heading)
    header: list[str] | None = None
    rows: list[dict[str, str]] = []
    for line in lines[start + 1 :]:
        if line.startswith("## "):
            break
        if not line.startswith("|"):
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if header is None:
            header = cells
            continue
        if all(set(cell) <= {"-", ":", " "} for cell in cells):
            continue
        if len(cells) != len(header):
            raise AssertionError("ragged table row: %r" % line)
        rows.append(dict(zip(header, cells)))
    if header is None:
        raise AssertionError("no table under %r" % heading)
    return rows


def _inventory_rows(text: str) -> list[dict[str, str]]:
    return _parse_table(text, "## Asset inventory")


def _write_manifest(root: Path, rel: str, payload) -> Path:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    return path


def _cc0_row(asset_id: str, path: str) -> dict:
    return {
        "provenance_id": asset_id,
        "kind": "image",
        "licence": "CC0-1.0",
        "path": path,
        "source": "authored:test-fixture",
    }


class NoticesInventoryTest(unittest.TestCase):
    def test_committed_file_is_generated_bytes(self):
        self.assertTrue(NOTICES.is_file(), "docs/launch/NOTICES.md is missing")
        self.assertEqual(
            NOTICES.read_text(encoding="utf-8"),
            GEN.render(ROOT),
            "docs/launch/NOTICES.md is stale; run `python3 scripts/gen-notices.py`",
        )

    def test_check_mode_reports_zero_diff(self):
        import subprocess

        proc = subprocess.run(
            [sys.executable, str(GENERATOR), "--check"],
            cwd=str(ROOT),
            capture_output=True,
            text=True,
        )
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        self.assertIn("0 diff lines", proc.stdout)

    def test_one_notices_row_per_manifest_row(self):
        entries = GEN.collect_rows(ROOT)
        parsed = _inventory_rows(NOTICES.read_text(encoding="utf-8"))
        self.assertEqual(len(parsed), len(entries))
        self.assertEqual(
            Counter(_plain(row["Asset id"]) for row in parsed),
            Counter(entry.asset_id for entry in entries),
            "the notices table and the manifests disagree about which assets exist",
        )
        ids = [entry.asset_id for entry in entries]
        self.assertEqual(len(ids), len(set(ids)), "a provenance id repeats across manifests")

    def test_header_names_and_pins_every_manifest(self):
        text = NOTICES.read_text(encoding="utf-8")
        rows = _parse_table(text, "## Generated from")
        by_input = {_plain(row["Input manifest"]): row for row in rows}
        manifests = GEN.manifest_paths(ROOT)
        self.assertEqual(set(by_input), {p.relative_to(ROOT).as_posix() for p in manifests})
        for path in manifests:
            rel = path.relative_to(ROOT).as_posix()
            row = by_input[rel]
            self.assertEqual(
                int(row["Rows"]),
                sum(1 for entry in GEN.collect_rows(ROOT) if entry.manifest == rel),
                "%s row count in the header is wrong" % rel,
            )
            self.assertEqual(
                _plain(row["sha256"]),
                hashlib.sha256(path.read_bytes()).hexdigest(),
                "%s sha256 in the header is wrong" % rel,
            )

    def test_added_manifest_entry_without_a_notices_row_is_drift(self):
        """A manifest row added without regenerating NOTICES.md must fail the inventory."""
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _write_manifest(
                root,
                "assets/first/manifest.json",
                [_cc0_row("fixture.first", "assets/first/first.webp")],
            )
            second = _write_manifest(
                root,
                "assets/second/manifest.json",
                [_cc0_row("fixture.second", "assets/second/second.webp")],
            )
            committed = GEN.render(root)
            self.assertEqual(len(_inventory_rows(committed)), 2)
            self.assertEqual(
                committed,
                GEN.render(root),
                "the generator is not deterministic for a fixed input tree",
            )

            payload = json.loads(second.read_text(encoding="utf-8"))
            payload.append(_cc0_row("fixture.second.added", "assets/second/added.webp"))
            second.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")

            entries = GEN.collect_rows(root)
            self.assertEqual(len(entries), 3)
            committed_ids = {_plain(row["Asset id"]) for row in _inventory_rows(committed)}
            added = {entry.asset_id for entry in entries} - committed_ids
            self.assertEqual(added, {"fixture.second.added"})
            self.assertNotEqual(
                GEN.render(root),
                committed,
                "the generator ignored an added manifest row; the notices check could not fail",
            )

    def test_unknown_licence_is_reported_not_invented(self):
        """A missing or unregistered licence id is UNKNOWN, with the reason in the evidence cell."""
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _write_manifest(
                root,
                "assets/odd/manifest.json",
                [
                    {"provenance_id": "fixture.no-licence", "kind": "image", "path": "a.webp"},
                    {
                        "provenance_id": "fixture.unknown-id",
                        "kind": "image",
                        "licence": "CC-BY-9.9",
                        "path": "b.webp",
                    },
                    {
                        "provenance_id": "fixture.missing-file",
                        "kind": "font",
                        "licence": "OFL-1.1",
                        "licence_file": "assets/odd/licenses/absent.txt",
                        "path": "c.woff2",
                    },
                ],
            )
            entries = GEN.collect_rows(root)
            self.assertEqual(
                {entry.licence for entry in entries},
                {"UNKNOWN", "CC-BY-9.9", "OFL-1.1"},
                "a declared id must be shown as declared, not replaced",
            )
            for entry in entries:
                self.assertFalse(entry.resolved)
                self.assertEqual(entry.commercial_use, "UNKNOWN")
                self.assertTrue(
                    entry.evidence.startswith("UNKNOWN"),
                    "an unresolved row must say why in its evidence cell: %r" % entry.evidence,
                )
            rendered = GEN.render(root)
            self.assertEqual(
                sum(
                    1
                    for row in _inventory_rows(rendered)
                    if _plain(row["Licence"]) == "UNKNOWN"
                    or row["Commercial use"] == "UNKNOWN"
                ),
                3,
                "each unresolved row should be visible as such",
            )
            self.assertIn("rows with an unresolved licence: 3", rendered)

    def test_declared_licence_files_exist_and_name_the_licence(self):
        for row in GEN.collect_rows(ROOT):
            if not row.evidence.startswith("`"):
                continue
            rel = _plain(row.evidence.split("`")[1])
            path = ROOT / rel
            self.assertTrue(
                path.is_file(), "%s declares %s, which is not committed" % (row.asset_id, rel)
            )
            if row.licence in GEN.LICENCE_TEXT_MARKERS:
                self.assertIn(
                    GEN.LICENCE_TEXT_MARKERS[row.licence], path.read_text(encoding="utf-8")
                )

    def test_commercial_use_only_comes_from_the_registry(self):
        for row in GEN.collect_rows(ROOT):
            if row.resolved:
                self.assertIn(row.licence, GEN.LICENCE_REGISTRY)
                self.assertEqual(
                    row.commercial_use, GEN.LICENCE_REGISTRY[row.licence].commercial_use
                )
            else:
                self.assertEqual(row.commercial_use, "UNKNOWN")
                self.assertNotIn(
                    row.licence,
                    GEN.LICENCE_REGISTRY,
                    "an unresolved row must not carry a registry licence id",
                )


if __name__ == "__main__":  # pragma: no cover
    unittest.main()
