"""Private ``node_modules`` staging for the desktop render harnesses.

Every desktop harness renders ``desktop/plugin.js`` with ``react-dom/server`` and a
stub ``@hermes/plugin-sdk``. The stub has to be a file the harness owns: the host
install's ``node_modules`` is shared by every worktree, every suite, and every agent
on the machine, so a stub written through a symlink into that tree mutates another
run's dependency while it is rendering (H-208 saw ``ToggleRow`` disappear from
``@hermes/plugin-sdk`` mid-suite for exactly this reason).

``stage_desktop_node_modules`` therefore builds a real ``node_modules`` directory
inside the caller's temporary root: each host package is symlinked in by name, but
``@hermes/plugin-sdk`` is a real directory under the temp root. Stub writes stay
inside the temp root and are cleaned up with it.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

#: Packages the harnesses themselves import. Anything they pull in transitively
#: resolves from the symlinked package's real location, so only top-level imports
#: matter here. Other host entries are mirrored too, so a harness that grows a new
#: top-level import still resolves it without touching the host tree.
HARNESS_PACKAGES = ("react", "react-dom", "scheduler", "jsdom")

SDK_PACKAGE_JSON = json.dumps(
    {"name": "@hermes/plugin-sdk", "type": "module", "main": "index.js"}
)


def desktop_node_modules() -> Path | None:
    """Return the host ``node_modules`` that has react and react-dom, if any."""
    candidates = [
        os.environ.get("HERMES_DESKTOP_APP"),
        str(Path.home() / ".hermes" / "hermes-agent" / "apps" / "desktop"),
        str(Path.home() / ".hermes" / "hermes-agent"),
    ]
    for candidate in candidates:
        if not candidate:
            continue
        react = Path(candidate) / "node_modules" / "react"
        server = Path(candidate) / "node_modules" / "react-dom" / "server.js"
        if react.is_dir() and server.is_file():
            return Path(candidate) / "node_modules"
    return None


def _link(source: Path, target: Path) -> None:
    if target.exists() or target.is_symlink():
        return
    target.symlink_to(source, target_is_directory=source.is_dir())


def stage_desktop_node_modules(root: Path | str) -> Path | None:
    """Create ``<root>/node_modules`` owned by the caller and return the SDK dir.

    The returned directory is always a real path inside ``root``; nothing this
    function creates can write into the host ``node_modules``. Returns ``None``
    when the host install has no usable react/react-dom (callers skip).
    """
    modules = desktop_node_modules()
    if modules is None:
        return None
    root = Path(root)
    node_modules = root / "node_modules"
    node_modules.mkdir(parents=True, exist_ok=True)

    for entry in sorted(modules.iterdir()):
        if entry.name == "@hermes":
            # The scope directory must be real so plugin-sdk can be local while
            # the host's other @hermes packages stay resolvable.
            scope = node_modules / "@hermes"
            scope.mkdir(exist_ok=True)
            if entry.is_dir():
                for child in sorted(entry.iterdir()):
                    if child.name == "plugin-sdk":
                        continue
                    _link(child, scope / child.name)
            continue
        _link(entry, node_modules / entry.name)

    sdk = node_modules / "@hermes" / "plugin-sdk"
    sdk.mkdir(parents=True, exist_ok=True)
    (sdk / "package.json").write_text(SDK_PACKAGE_JSON, encoding="utf-8")
    return sdk


def write_sdk_stub(root: Path | str, stub: str) -> Path:
    """Write ``stub`` as the private plugin-sdk ``index.js`` under ``root``."""
    sdk = Path(root) / "node_modules" / "@hermes" / "plugin-sdk"
    sdk.mkdir(parents=True, exist_ok=True)
    (sdk / "package.json").write_text(SDK_PACKAGE_JSON, encoding="utf-8")
    index = sdk / "index.js"
    index.write_text(stub, encoding="utf-8")
    return index
